#!/usr/bin/env bash
# Step 3: pack BusyBox into an LZMA-compressed initramfs (newc cpio).
source "$(dirname "$0")/common.sh"
need cpio lzma

BB_DIR="$BUILD_DIR/busybox"
FS="$BUILD_DIR/fs"
[ -x "$BB_DIR/busybox" ] || die "Build BusyBox first: bash scripts/02-busybox.sh"

log "Creating root filesystem in $FS"
rm -rf "$FS"
mkdir -p "$FS/bin"
cp "$BB_DIR/busybox" "$FS/busybox"
cd "$FS"

# BusyBox picks the applet from argv[0]. A hard link named "sh" makes the
# kernel's rdinit=/sh start the ash shell, and costs no extra space.
ln busybox sh

# Same trick for every other applet, placed in /bin so ash finds them via
# its default PATH. busybox.links is generated by the BusyBox build.
while read -r path; do
	name="$(basename "$path")"
	[ "$name" = sh ] && continue
	ln busybox "bin/$name"
done < "$BB_DIR/busybox.links"

ls -l "$FS" "$FS/bin"

log "Building init.cpio"
# -R root:root: files inside the image belong to root, not to your WSL user.
# The kernel adds /dev/console from its own built-in initramfs.
find . -print0 | cpio --null -o --format=newc -R root:root > "$BUILD_DIR/init.cpio"

log "Compressing with LZMA"
# A 1 MiB dictionary is plenty for a <1 MiB archive, and keeps the kernel's
# decompressor from allocating the 64 MiB that preset 9 would ask for.
lzma -z -k -f --lzma1=preset=9e,dict=1MiB "$BUILD_DIR/init.cpio"

cp "$BUILD_DIR/init.cpio.lzma" "$OUT_DIR/init.cpio.lzma"
log "initramfs ready: $OUT_DIR/init.cpio.lzma" \
    "($(human "$(stat -c %s "$BUILD_DIR/init.cpio")") -> $(human "$(stat -c %s "$OUT_DIR/init.cpio.lzma")"))"
